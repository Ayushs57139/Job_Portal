// Helper function to get regions for a state
export const getRegionsByState = (stateValue) => {
  if (!stateValue) return [];
  
  // Handle both string values and object values
  const normalizedState = typeof stateValue === 'string' 
    ? stateValue 
    : (stateValue.value || stateValue.label || '');
  
  return stateRegionsMap[normalizedState] || [];
};

// Export all regions as a flat list for reference
export const getAllRegions = () => {
  const allRegions = [];
  Object.values(stateRegionsMap).forEach(regions => {
    allRegions.push(...regions);
  });
  return allRegions;
};

